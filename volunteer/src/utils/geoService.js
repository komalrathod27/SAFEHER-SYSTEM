export async function fetchLiveIPLocation() {
  try {
    const res = await fetch("https://ipwho.is/", {
      signal: AbortSignal.timeout ? AbortSignal.timeout(3500) : undefined,
    });
    if (res.ok) {
      const data = await res.json();
      if (data && data.success && data.latitude && data.longitude) {
        return {
          lat: data.latitude,
          lng: data.longitude,
          city: data.city || "",
          state: data.region || "",
        };
      }
    }
  } catch {}
  return null;
}

export async function reverseGeocode(lat, lng) {
  if (!lat || !lng) return "Live GPS Location";
  try {
    const url = `https://nominatim.openstreetmap.org/reverse?format=json&lat=${lat}&lon=${lng}&zoom=16&addressdetails=1`;
    const res = await fetch(url, {
      headers: {
        "Accept-Language": "en",
        "User-Agent": "SafeHer-Emergency-System/1.0 (contact@safeher.org)",
      },
      signal: AbortSignal.timeout ? AbortSignal.timeout(3500) : undefined,
    });
    if (res.ok) {
      const data = await res.json();
      if (data && data.address) {
        const a = data.address;
        const parts = [
          a.road || a.suburb || a.neighbourhood,
          a.city || a.town || a.village || a.county,
          a.state_district,
          a.state,
          a.postcode,
        ].filter(Boolean);
        if (parts.length > 0) return parts.join(", ");
        if (data.display_name) return data.display_name.split(",").slice(0, 4).join(", ");
      }
    }
  } catch {}
  return `Live Coordinates (${Number(lat).toFixed(4)}, ${Number(lng).toFixed(4)})`;
}

export function getUserCityFallback(user) {
  const city = (user?.city || "").trim().toLowerCase();
  if (city && ALL_INDIA_CITIES[city]) {
    const c = ALL_INDIA_CITIES[city];
    return { lat: c.lat, lng: c.lng, address: `${c.name}, ${c.state}` };
  }
  return { lat: 28.6139, lng: 77.2090, address: "New Delhi, India" };
}

export async function getAccurateLocation(user) {
  if (typeof navigator !== "undefined" && navigator.geolocation) {
    try {
      const pos = await new Promise((resolve, reject) => {
        navigator.geolocation.getCurrentPosition(resolve, reject, {
          enableHighAccuracy: true,
          timeout: 15000,
          maximumAge: 0,
        });
      });
      const lat = pos.coords.latitude;
      const lng = pos.coords.longitude;
      const address = await reverseGeocode(lat, lng);
      return { lat, lng, address, accuracy: pos.coords.accuracy || 0 };
    } catch {}
  }
  const ipLoc = await fetchLiveIPLocation();
  if (ipLoc) {
    const address = await reverseGeocode(ipLoc.lat, ipLoc.lng);
    return { lat: ipLoc.lat, lng: ipLoc.lng, address, accuracy: 1000 };
  }
  const fallback = getUserCityFallback(user);
  return { lat: fallback.lat, lng: fallback.lng, address: fallback.address, accuracy: 5000 };
}
